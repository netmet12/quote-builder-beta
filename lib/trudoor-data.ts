// Convert TRUDOOR_DATA to ProductType format for compatibility
export function getTrudoorProductTypes(): TrudoorProductType[] {
  const productTypes: TrudoorProductType[] = []

  Object.entries(TRUDOOR_DATA._types).forEach(([typeId, typeName]) => {
    const sections = TRUDOOR_DATA.sections[typeId]
    if (sections && Object.keys(sections).length > 0) {
      productTypes.push({
        id: Number.parseInt(typeId),
        name: typeName,
        description: TRUDOOR_DATA._type_descriptions[typeId] || "",
        image: TRUDOOR_DATA._type_images[typeId] || "/placeholder.svg?height=300&width=300",
        sections: sections,
        totalSections: TRUDOOR_DATA._type_sections[typeId] || 0,
      })
    }
  })

  return productTypes
}

