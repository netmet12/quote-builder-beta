export function getTrudoorProductTypes() {
  return Object.entries(TRUDOOR_COMPLETE_DATA._types)
    .map(([id, name]) => ({
      id,
      name,
      description: TRUDOOR_COMPLETE_DATA._type_descriptions[id] || "",
      image: TRUDOOR_COMPLETE_DATA._type_images[id] || "",
      sectionCount: TRUDOOR_COMPLETE_DATA._type_sections[id] || 0,
    }))
    .filter((product) => product.sectionCount > 0)
}

export function getTrudoorSections(productTypeId: string) {
  return TRUDOOR_COMPLETE_DATA.sections[productTypeId] || {}
}

export function evaluateTrudoorConditions(conditions: any[], selections: Record<string, any>): boolean {
  if (!conditions || conditions.length === 0) return true

  return conditions.some((conditionGroup) => {
    if (Array.isArray(conditionGroup)) {
      return conditionGroup.every((condition) => evaluateSingleCondition(condition, selections))
    }
    return evaluateSingleCondition(conditionGroup, selections)
  })
}

function evaluateSingleCondition(condition: any, selections: Record<string, any>): boolean {
  const { section, options, condition: conditionType } = condition
  const sectionSelection = selections[section]

  if (!sectionSelection) return false

  const selectedOptions = Array.isArray(sectionSelection) ? sectionSelection : [sectionSelection]

  switch (conditionType) {
    case "IN":
      return options.some((opt: any) => selectedOptions.includes(opt))
    case "NOT":
      return !options.some((opt: any) => selectedOptions.includes(opt))
    case "NOT_MULTI":
      return !options.every((opt: any) => selectedOptions.includes(opt))
    default:
      return options.some((opt: any) => selectedOptions.includes(opt))
  }
}
